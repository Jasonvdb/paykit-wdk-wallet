#!/usr/bin/env node
// Turn the git-ignored .env.demo into the git-ignored src/config/demo.local.ts
// that dev builds read to prefill each simulator's identity.
//
// .env.demo keys:
//   IOS_SIGNUP_CODE, ANDROID_SIGNUP_CODE   single-use Pubky staging signup codes
//   IOS_MNEMONIC, ANDROID_MNEMONIC         BIP-39 phrases for the two identities
//   IOS_PUBKY, ANDROID_PUBKY               public keys, recorded after signup; each
//                                          platform gets the other one as its peer
//
// With --generate-missing, a missing mnemonic is generated here (12 words,
// CSPRNG) and appended to .env.demo, so a reinstall restores the same
// identity and signs in without spending a new signup code.
//
// This script never prints secret values. Both files are written with mode 600.
import { appendFileSync, chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateMnemonic } from '@scure/bip39';
import { wordlist } from '@scure/bip39/wordlists/english.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, '.env.demo');
const outPath = join(root, 'src/config/demo.local.ts');
const generateMissing = process.argv.includes('--generate-missing');

function parseEnv(text) {
  const values = {};
  for (const line of text.split('\n')) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (match) values[match[1]] = match[2].replace(/^["']|["']$/g, '');
  }
  return values;
}

if (!existsSync(envPath)) {
  console.error('No .env.demo found; nothing to do.');
  process.exit(1);
}
let env = parseEnv(readFileSync(envPath, 'utf8'));

for (const key of ['IOS_MNEMONIC', 'ANDROID_MNEMONIC']) {
  if (env[key]) continue;
  if (!generateMissing) {
    console.log(`${key} is not set (run with --generate-missing to create it).`);
    continue;
  }
  const phrase = generateMnemonic(wordlist, 128);
  appendFileSync(envPath, `${key}=${phrase}\n`);
  console.log(`Generated ${key} and appended it to .env.demo.`);
}
chmodSync(envPath, 0o600);
env = parseEnv(readFileSync(envPath, 'utf8'));

const prefill = (prefix, peerPrefix) => ({
  mnemonic: env[`${prefix}_MNEMONIC`] || undefined,
  signupCode: env[`${prefix}_SIGNUP_CODE`] || undefined,
  peerPubky: env[`${peerPrefix}_PUBKY`] || undefined,
});
const body = {
  ios: prefill('IOS', 'ANDROID'),
  android: prefill('ANDROID', 'IOS'),
};
writeFileSync(
  outPath,
  '// GENERATED by scripts/demo-env.mjs from .env.demo. Git-ignored: never commit.\n' +
    `const demoLocal = ${JSON.stringify(body, null, 2)};\nexport default demoLocal;\n`,
  { mode: 0o600 },
);
chmodSync(outPath, 0o600);
const present = (p) => Object.entries(p).filter(([, v]) => v).map(([k]) => k).join(', ') || 'none';
console.log(`Wrote src/config/demo.local.ts (ios: ${present(body.ios)}; android: ${present(body.android)}).`);
